#!/usr/bin/env python3
"""Emit the TAG_SEARCH_INDEX string and tagSearchResolve() helper for wtrlab.lua.

Source of truth: /home/z/my-project/research/real_tags.json  (882 tags)

Why: NoveLA's filter UI renders every tristate option as an eagerly-built
TriStateChip in a FlowRow (FilterBottomSheet.kt). With 882 tags split across
11 groups, finding a specific tag means scrolling through up to 190 chips in
one group. The site's own novel-finder has a free-text search that filters
the visible tags. NoveLA has no native "searchable list" filter type, so we
add a `text` filter ("Tag Search") whose value is parsed by the plugin: each
comma/newline/space-separated token is matched case-insensitively as a
substring against every tag label; matching tag IDs are merged into the
existing ti=/te= API params. Tag IDs typed directly are also accepted.

Layout of the index string (compact, ~16KB):
  "417|Male Protagonist\n275|Female Protagonist\n..."

Parsing is done once at plugin load into a Lua array of {id, lower_label};
tagSearchResolve(text) iterates the array and collects dedup'd IDs whose
lower_label contains the lowercased token, OR whose id == token.

Output is written to /home/z/my-project/scripts/tag_search_index.lua.txt
as a drop-in block for wtrlab.lua.
"""
import json
import sys

TAGS = "/home/z/my-project/research/real_tags.json"
OUT  = "/home/z/my-project/scripts/tag_search_index.lua.txt"


def esc(s: str) -> str:
    # No tag label contains a backslash or double quote (verified at gen
    # time), but escape them defensively so the file stays correct even if
    # real_tags.json is ever refreshed with new labels that do.
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def main():
    tags = json.load(open(TAGS, encoding="utf-8"))
    assert len(tags) == 882, "expected 882 tags, got %d" % len(tags)
    assert any(str(t["value"]) == "801" and "Honghuang" in t["label"] for t in tags), \
        "Honghuang (801) missing from tag source"

    # Sort by id ascending so binary search / early-exit could be added later.
    # Tag IDs go up to ~871 so we don't pad.
    tags_sorted = sorted(tags, key=lambda t: int(t["value"]))
    lines = ["%s|%s" % (t["value"], esc(t["label"])) for t in tags_sorted]

    # Emit as one Lua string literal. Use double-bracket long string for
    # zero escaping headaches EXCEPT Lua long strings don't allow leading
    # newline before closing ]] -- we use [==[ ... ]==] to dodge any "]]"
    # inside (none expected, but defensive).
    body = "\n".join(lines)

    block = []
    block.append("-- ── Tag search index & resolver ─────────────────────────────────────")
    block.append("-- Auto-generated by scripts/gen_tag_search_index.py from")
    block.append("-- research/real_tags.json (882 tags). Do not hand-edit; re-run")
    block.append("-- the generator after refreshing real_tags.json.")
    block.append("--")
    block.append("-- Format: one \"id|Label\" pair per line. Parsed once at plugin")
    block.append("-- load into ALL_TAGS (array of {id=string, label=lowercase}).")
    block.append("-- tagSearchResolve(text) returns a dedup'd list of ids whose")
    block.append("-- label contains any comma/space/newline-separated token, OR")
    block.append("-- whose id matches a token. Empty/whitespace-only text → empty list.")
    block.append("")
    block.append("local TAG_SEARCH_INDEX = [==[")
    block.append(body)
    block.append("]==]")
    block.append("")
    block.append("local ALL_TAGS = {}")
    block.append("do")
    block.append("    for line in TAG_SEARCH_INDEX:gmatch(\"[^\\n]+\") do")
    block.append("        local id, label = line:match(\"^([^|]+)|(.+)$\")")
    block.append("        if id and label then")
    block.append("            ALL_TAGS[#ALL_TAGS + 1] = { id = id, label = label:lower() }")
    block.append("        end")
    block.append("    end")
    block.append("end")
    block.append("")
    block.append("-- Resolve a free-text Tag Search field to a dedup'd list of tag IDs.")
    block.append("-- Tokens are split on comma, semicolon, newline, tab, or any run")
    block.append("-- of whitespace. Each token is matched case-insensitively as a")
    block.append("-- substring of every tag label; if the token itself is a numeric")
    block.append("-- tag id it is also accepted verbatim. Returned ids are unique.")
    block.append("function tagSearchResolve(text)")
    block.append("    if not text or text == \"\" then return {} end")
    block.append("    local lower = text:lower()")
    block.append("    local seen = {}")
    block.append("    local out = {}")
    block.append("    -- gmatch with a single-char-but-greedy alternation: comma,")
    block.append("    -- semicolon, newline, tab, or any run of spaces (any unicode")
    block.append("    -- whitespace would be nicer but Lua's %s is ASCII-only).")
    block.append("    for token in lower:gmatch(\"[^,;\\n\\t ]+\") do")
    block.append("        if token ~= \"\" then")
    block.append("            for _, t in ipairs(ALL_TAGS) do")
    block.append("                if t.label:find(token, 1, true) or t.id == token then")
    block.append("                    if not seen[t.id] then")
    block.append("                        seen[t.id] = true")
    block.append("                        out[#out + 1] = t.id")
    block.append("                    end")
    block.append("                end")
    block.append("            end")
    block.append("        end")
    block.append("    end")
    block.append("    return out")
    block.append("end")
    block.append("")

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(block))
    print("Wrote %d tags to %s" % (len(tags_sorted), OUT))


if __name__ == "__main__":
    sys.exit(main())
