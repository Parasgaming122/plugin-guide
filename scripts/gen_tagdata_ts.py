#!/usr/bin/env python3
"""Generate src/lib/tagData.ts for the WTR-LAB novel finder prototype.

Sources:
  - research/tags_live_v3.json  (live /en/novel-finder __NEXT_DATA__ tags block:
                                 888 tags + 11 category groups, captured 2026-09-03)
  - download/wtrlab.lua         (filter option lists — finder param parity)

Site category display order (as rendered on wtr-lab.com/en/novel-finder sidebar):
  1, 10, 2, 4, 3, 6, 7, 5, 8, 9, 11
"""
import json
import re
from pathlib import Path

ROOT = Path("/home/z/my-project")
TAGS_JSON = ROOT / "research/tags_live_v3.json"
PLUGIN = ROOT / "download/wtrlab.lua"
OUT = ROOT / "src/lib/tagData.ts"

SITE_CATEGORY_ORDER = [1, 10, 2, 4, 3, 6, 7, 5, 8, 9, 11]

data = json.loads(TAGS_JSON.read_text(encoding="utf-8"))
ungrouped = data["ungrouped"]
groups = {g["id"]: g["name"] for g in data["groups"]}

assert len(ungrouped) == 888, f"expected 888 tags, got {len(ungrouped)}"
assert len(groups) == 11, f"expected 11 groups, got {len(groups)}"

# ── tags sorted alphabetically within each category (site renders alphabetical) ──
by_cat: dict[int, list[dict]] = {}
for t in ungrouped:
    by_cat.setdefault(t["category_id"], []).append(
        {"id": t["value"], "label": t["label"]}
    )

for cat in by_cat:
    by_cat[cat].sort(key=lambda x: x["label"].lower())

categories = [
    {"id": cid, "name": groups[cid], "tags": by_cat.get(cid, [])}
    for cid in SITE_CATEGORY_ORDER
]

# ── genres + option lists from the plugin's filter sheet (finder parity) ──
plugin = PLUGIN.read_text(encoding="utf-8")

def extract_options(key: str) -> list[tuple[str, str]]:
    m = re.search(r'key = "' + key + r'".*?options = \{(.*?)\n\s*\},', plugin, re.S)
    body = m.group(1)
    # skip the plugin's {value = "", label = "Any"} rows — SelectFilter renders
    # its own "Any" sentinel item (Radix forbids empty-string SelectItem values)
    return [
        (v, l)
        for v, l in re.findall(r'\{value = "([^"]*)", label = "([^"]*)"\}', body)
        if v != ""
    ]

genres = extract_options("genres")
assert len(genres) == 40, f"expected 40 genres, got {len(genres)}"

order_by = extract_options("orderBy")
status_opts = extract_options("status")
release_status = extract_options("release_status")
addition_age = extract_options("addition_age")
count_chapters = extract_options("count_chapters")
count_characters = extract_options("count_characters")
min_rating = extract_options("min_rating")
min_reviews = extract_options("min_reviews")


def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def ts_options(pairs, typename: str) -> str:
    rows = ",\n".join(f'  {{ value: "{esc(v)}", label: "{esc(l)}" }}' for v, l in pairs)
    return f"export const {typename}: FinderOption[] = [\n{rows},\n];"


parts = []
parts.append("""// ─────────────────────────────────────────────────────────────────────────────
// WTR-LAB tag / category / filter-option data
// Auto-generated by scripts/gen_tagdata_ts.py — do not hand-edit.
// Sources: research/tags_live_v3.json (live capture 2026-09-03, 888 tags),
// download/wtrlab.lua filter sheet (finder param parity).
// ─────────────────────────────────────────────────────────────────────────────

export interface FinderOption {
  value: string;
  label: string;
}

export interface TagDef {
  id: number;
  label: string;
  lower: string;
}

export interface TagCategory {
  id: number;
  name: string;
  tags: TagDef[];
}
""")

cat_chunks = []
for c in categories:
    tag_rows = ",\n".join(
        f'    {{ id: {t["id"]}, label: "{esc(t["label"])}", lower: "{esc(t["label"].lower())}" }}'
        for t in c["tags"]
    )
    cat_chunks.append(
        f'  {{\n    id: {c["id"]},\n    name: "{esc(c["name"])}",\n    tags: [\n{tag_rows},\n    ],\n  }}'
    )

parts.append("export const TAG_CATEGORIES: TagCategory[] = [\n" + ",\n".join(cat_chunks) + ",\n];")

# flat tag map for card rendering (id → label)
parts.append(
    "export const ALL_TAGS: TagDef[] = TAG_CATEGORIES.flatMap((c) => c.tags);\n\n"
    "export const TAG_BY_ID: Map<number, TagDef> = new Map(ALL_TAGS.map((t) => [t.id, t]));\n\n"
    "export const CATEGORY_BY_ID: Map<number, string> = new Map(\n"
    "  TAG_CATEGORIES.map((c) => [c.id, c.name]),\n"
    ");"
)

genre_rows = ",\n".join(f'  {{ id: {v}, label: "{esc(l)}" }}' for v, l in genres)
parts.append(f"export interface GenreDef {{ id: number; label: string; lower: string }}\n\nexport const GENRES: GenreDef[] = [\n{genre_rows},\n];")

parts.append(ts_options(order_by, "ORDER_BY_OPTIONS"))
parts.append(ts_options(status_opts, "STATUS_OPTIONS"))
parts.append(ts_options(release_status, "RELEASE_STATUS_OPTIONS"))
parts.append(ts_options(addition_age, "ADDITION_AGE_OPTIONS"))
parts.append(ts_options(count_chapters, "CHAPTER_COUNT_OPTIONS"))
parts.append(ts_options(count_characters, "CHARACTER_COUNT_OPTIONS"))
parts.append(ts_options(min_rating, "MIN_RATING_OPTIONS"))
parts.append(ts_options(min_reviews, "MIN_REVIEWS_OPTIONS"))

parts.append("""export const STATUS_LABELS: Record<number, string> = {
  0: "Ongoing",
  1: "Completed",
  2: "Hiatus",
  3: "Dropped",
};""")

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n\n".join(parts) + "\n", encoding="utf-8")

total = sum(len(c["tags"]) for c in categories)
print(f"wrote {OUT} — {len(categories)} categories, {total} tags, {len(genres)} genres")
