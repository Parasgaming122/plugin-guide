#!/usr/bin/env python3
"""Swap the wtrlab.lua tag-search block (index + parser + resolver) for v2.

Replaces the region from the '-- ── Tag search index & resolver' comment
through the end of the old tagSearchResolve function with the new
category-aware index (id|Label|cat) and phrase-capable resolver.
"""
import re

PLUGIN = '/home/z/my-project/download/wtrlab.lua'
INDEX = '/home/z/my-project/scripts/tag_search_index_v2.lua.txt'

src = open(PLUGIN, encoding='utf-8').read()
index_lines = open(INDEX, encoding='utf-8').read().strip('\n')

# ── locate the region ──────────────────────────────────────────────────────
start_marker = "-- ── Tag search index & resolver ─────────────────────────────────────\n"
start = src.index(start_marker)
# end: the line after the old resolver's final 'end' (before "-- ── Catalog ──")
end_marker = "\n-- ── Catalog ─────────────────────────────────────────────────────────────────\n"
end = src.index(end_marker)

new_block = '''-- ── Tag search index & resolver (v2) ─────────────────────────────────────
-- Auto-generated by scripts/gen_tag_search_index_v2.py from the live
-- /en/novel-finder __NEXT_DATA__ snapshot (research/tags_live_v2.json;
-- 888 tags as of 2026-09-03). Do not hand-edit; re-run the generator
-- after refreshing the snapshot.
--
-- Format: one "id|Label|catId" triple per line. Parsed once at plugin
-- load into ALL_TAGS ({id, label=lowercase, cat}); TAG_CATEGORIES holds
-- the 11 site category names for the Tag Search Category picker.
--
-- tagSearchResolve(text, cat) → dedup'd list of tag ids matching any
-- comma/semicolon-separated token (multi-word tokens match as phrases
-- first, per-word as fallback; numeric tokens are ids). cat scopes
-- matching to one category ("0"/nil = all categories).

local TAG_CATEGORIES = {
    { id = "0",  label = "All Categories" },
    { id = "1",  label = "Protagonist Archetypes (190)" },
    { id = "2",  label = "Power Systems (100)" },
    { id = "3",  label = "Worldbuilding (56)" },
    { id = "4",  label = "Socio-Political Structures (71)" },
    { id = "5",  label = "Relationship Tropes (136)" },
    { id = "6",  label = "Narrative (46)" },
    { id = "7",  label = "Beings & Factions (68)" },
    { id = "8",  label = "Professional Archetypes (64)" },
    { id = "9",  label = "Tone & Atmosphere (27)" },
    { id = "10", label = "Adaptations (90)" },
    { id = "11", label = "Miscellaneous Narrative Elements (40)" },
}

local TAG_SEARCH_INDEX = [==[
''' + index_lines + '''
]==]

local ALL_TAGS = {}
do
    for line in TAG_SEARCH_INDEX:gmatch("[^\\n]+") do
        local id, label, cat = line:match("^([^|]+)|([^|]+)|([^|]+)$")
        if id and label and cat then
            ALL_TAGS[#ALL_TAGS + 1] = { id = id, label = label:lower(), cat = cat }
        end
    end
end

-- Resolve a free-text Tag Search field to a dedup'd list of tag IDs.
--   • Tokens are split on comma / semicolon / newline / tab; spaces are
--     kept INSIDE tokens so multi-word phrases work ("weak to strong").
--   • A multi-word token that matches no tag falls back to per-word
--     matching (so "reincarnation harem" still finds both tags).
--   • A numeric token is also accepted as a verbatim tag id.
--   • Matching is case-insensitive substring on the label.
--   • cat: "0"/nil = all categories, else a single category id ("1".."11")
--     — scopes the whole resolution (mirrors the site finder's grouping).
function tagSearchResolve(text, cat)
    if not text or text == "" then return {} end
    local catFilter = tostring(cat or "0")
    local scopeAll = (catFilter == "0" or catFilter == "" or catFilter == "all")
    local lower = text:lower()
    local seen = {}
    local out = {}

    local function collect(token)
        local n = 0
        for _, t in ipairs(ALL_TAGS) do
            if (scopeAll or t.cat == catFilter) and not seen[t.id] then
                if t.label:find(token, 1, true) or t.id == token then
                    seen[t.id] = true
                    out[#out + 1] = t.id
                    n = n + 1
                end
            end
        end
        return n
    end

    for rawToken in lower:gmatch("[^,;\\n\\t]+") do
        local token = rawToken:gsub("^%s+", ""):gsub("%s+$", "")
        if token ~= "" then
            if token:find("%s") then
                -- multi-word: whole phrase first, per-word fallback
                local n = collect(token)
                if n == 0 then
                    for word in token:gmatch("%S+") do
                        collect(word)
                    end
                end
            else
                collect(token)
            end
        end
    end
    return out
end
'''

src = src[:start] + new_block + src[end:]
open(PLUGIN, 'w', encoding='utf-8').write(src)
print(f"swapped: old region [{start}:{end}] → v2 block ({len(new_block)} chars)")
print(f"file is now {len(src.splitlines())} lines")
