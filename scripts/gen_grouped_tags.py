#!/usr/bin/env python3
"""Emit the 11 grouped tristate tag-filter blocks for wtrlab.lua.

Source of truth: /home/z/my-project/research/real_tags.json
  - list of {value, label, category_id, category}
  - 882 tags across 11 groups (matches wtr-lab.com/en/novel-finder
    pageProps.tags.groups + pageProps.tags.ungrouped).

NoveLA renders every tristate option as an eagerly-built TriStateChip in a
FlowRow (FilterBottomSheet.kt), so a single 882-item list is a literal wall
of chips. Splitting by the site's own category grouping gives 11 pickers of
27-190 chips each -- matching the site's own finder UX.

The app re-sorts options alphabetically within each filter, so emission order
inside a group does not affect display. The GROUP order (1..11) is the order
sections appear in the filter bottom sheet.

Output is written to /home/z/my-project/scripts/grouped_tags.lua.txt as a
drop-in replacement for the single `tags` tristate block in wtrlab.lua.
"""
import json
import sys

TAGS = "/home/z/my-project/research/real_tags.json"
OUT  = "/home/z/my-project/scripts/grouped_tags.lua.txt"

# (category_id, lua_key, human label) -- order = section order in the sheet.
# Keys are stable slugs so getCatalogFiltered can collect them deterministically.
GROUPS = [
    (1,  "tags_protagonist",     "Protagonist Archetypes"),
    (2,  "tags_power_systems",   "Power Systems"),
    (3,  "tags_worldbuilding",   "Worldbuilding"),
    (4,  "tags_socio_political", "Socio-Political Structures"),
    (5,  "tags_relationships",   "Relationship Tropes"),
    (6,  "tags_narrative",       "Narrative"),
    (7,  "tags_beings_factions", "Beings & Factions"),
    (8,  "tags_professional",    "Professional Archetypes"),
    (9,  "tags_tone",            "Tone & Atmosphere"),
    (10, "tags_adaptations",     "Adaptations"),
    (11, "tags_misc",            "Miscellaneous Narrative Elements"),
]

def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')

def lua_options(pairs, per_line=4, indent="                "):
    lines = []
    for i in range(0, len(pairs), per_line):
        chunk = pairs[i:i + per_line]
        lines.append(indent + " ".join(
            '{value = "%s", label = "%s"},' % (v, esc(l)) for v, l in chunk))
    return "\n".join(lines)

def main():
    tags = json.load(open(TAGS, encoding="utf-8"))
    assert len(tags) == 882, "expected 882 tags, got %d" % len(tags)
    # honghuang sanity check
    assert any(str(t["value"]) == "801" and "Honghuang" in t["label"] for t in tags), \
        "Honghuang (801) missing from tag source"

    by_cat = {}
    for t in tags:
        by_cat.setdefault(t["category_id"], []).append((str(t["value"]), t["label"]))

    blocks = []
    total = 0
    for cat_id, key, label in GROUPS:
        entries = sorted(by_cat.get(cat_id, []), key=lambda x: x[1].lower())
        total += len(entries)
        # Label includes the count so the user knows how many chips each picker
        # will render before opening it (counts auto-update on re-run).
        header = '%s (%d)' % (label, len(entries))
        opts = lua_options(entries, per_line=3)
        block = (
            '        {\n'
            '            type = "tristate",\n'
            '            key = "%s",\n'
            '            label = "%s",\n'
            '            options = {\n'
            '%s\n'
            '            }\n'
            '        },\n'
        ) % (key, header, opts)
        blocks.append(block)

    out = "-- 11 grouped tag filters (auto-generated by scripts/gen_grouped_tags.py\n" \
          "--  from research/real_tags.json -- 882 tags across 11 site categories).\n" \
          "--  Do not hand-edit; re-run the generator after refreshing real_tags.json.\n"
    out += "\n".join(blocks) + "\n"

    with open(OUT, "w", encoding="utf-8") as f:
        f.write(out)
    print("Wrote %d tag groups, %d total tags to %s" % (len(GROUPS), total, OUT))
    assert total == 882, "total tag count mismatch: %d" % total

if __name__ == "__main__":
    sys.exit(main())
