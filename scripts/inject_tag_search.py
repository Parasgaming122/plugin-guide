#!/usr/bin/env python3
"""Inject the TAG_SEARCH_INDEX + tagSearchResolve helper, the two new text
filters (Tag Search include/exclude), and the resolver calls in
getCatalogFiltered into /home/z/my-project/download/wtrlab.lua.

Idempotent: detects whether the injection has already happened and skips.
"""
import sys

PLUGIN = "/home/z/my-project/download/wtrlab.lua"
INDEX_BLOCK = "/home/z/my-project/scripts/tag_search_index.lua.txt"

# Markers injected into the plugin; presence is the idempotency check.
HELPER_START_MARKER = "-- ── Tag search index & resolver ─────────────────────────────────────"
FILTER_MARKER = "-- Tag Search (free-text; resolves to tag IDs via tagSearchResolve)"

with open(PLUGIN, encoding="utf-8") as f:
    plugin = f.read()
with open(INDEX_BLOCK, encoding="utf-8") as f:
    index_block = f.read()

# Strip trailing newline from block so we can control spacing.
index_block = index_block.rstrip() + "\n"

# ── 1. Inject TAG_SEARCH_INDEX + tagSearchResolve helper ──────────────
# Insert right before "-- ── Catalog ──" line. The helper is the cleanest
# place because it sits with the other "before getCatalogList" helpers
# (pagePropsToResult, seriesToItems, fetchNextData, etc).
catalog_anchor = "-- ── Catalog ─────────────────────────────────────────────────────────────────"
if HELPER_START_MARKER in plugin:
    print("SKIP: TAG_SEARCH_INDEX already present in plugin")
else:
    assert catalog_anchor in plugin, "Catalog anchor not found; plugin structure changed?"
    # Insert with blank lines around for readability.
    injection = "\n" + index_block + "\n"
    plugin = plugin.replace(catalog_anchor, injection + catalog_anchor, 1)
    print("INSERTED: TAG_SEARCH_INDEX + tagSearchResolve helper before Catalog section")

# ── 2. Inject two `text` filters in getFilterList, before the 11 grouped tag blocks ──
# Anchor: the comment line right before the first `tags_protagonist` block.
grouped_anchor = "-- 11 grouped tag filters (auto-generated by scripts/gen_grouped_tags.py"
if FILTER_MARKER in plugin:
    print("SKIP: Tag Search text filters already present in plugin")
else:
    assert grouped_anchor in plugin, "Grouped tags anchor not found"
    # Build the two text filter entries. Indentation matches the surrounding
    # filter list (8 spaces for the table body inside getFilterList).
    text_filters = (
        "        " + FILTER_MARKER + "\n"
        "        {\n"
        "            type = \"text\",\n"
        "            key = \"tag_search_inc\",\n"
        "            label = \"Tag Search (include)\",\n"
        "            defaultValue = \"\"\n"
        "        },\n"
        "        {\n"
        "            type = \"text\",\n"
        "            key = \"tag_search_exc\",\n"
        "            label = \"Tag Search (exclude)\",\n"
        "            defaultValue = \"\"\n"
        "        },\n"
    )
    # Inject BEFORE the comment block that documents the 11 grouped filters,
    # so the search fields appear immediately under "Tag (And/Or)" in the
    # sheet — closest to the user's mental model of "filters for tags".
    plugin = plugin.replace(grouped_anchor, text_filters + grouped_anchor, 1)
    print("INSERTED: Tag Search text filters before 11 grouped tag blocks")

# ── 3. Inject resolver calls in getCatalogFiltered ────────────────────
# Anchor: the line `local tags_inc, tags_exc = {}, {}` (start of the tag
# collection). Insert a call right after the 11-group collection loop ends,
# so tag-search matches are merged into the same combined lists.
search_call_marker = "-- Tag Search: resolve free-text tokens to tag IDs and merge"
if search_call_marker in plugin:
    print("SKIP: tagSearchResolve calls already present in getCatalogFiltered")
else:
    # Anchor on the closing `end` of the 11-group collection loop. The loop
    # iterates the GROUP_KEYS list and pushes into tags_inc/tags_exc. The
    # `end` that closes it is the line right before `local params = `.
    anchor = '    local params = "orderBy=" .. orderBy'
    assert anchor in plugin, "getCatalogFiltered params anchor not found"
    # The merge: parse both text fields, extend tags_inc / tags_exc with
    # resolved ids (dedup'd by the resolver itself, but we dedup again
    # against the existing set to be safe).
    merge_block = (
        "    " + search_call_marker + "\n"
        "    for _, id in ipairs(tagSearchResolve(filters[\"tag_search_inc\"]) or {}) do\n"
        "        tags_inc[#tags_inc + 1] = id\n"
        "    end\n"
        "    for _, id in ipairs(tagSearchResolve(filters[\"tag_search_exc\"]) or {}) do\n"
        "        tags_exc[#tags_exc + 1] = id\n"
        "    end\n"
    )
    plugin = plugin.replace(anchor, merge_block + anchor, 1)
    print("INSERTED: tagSearchResolve calls in getCatalogFiltered")

# ── 4. Bump the version banner at the top ─────────────────────────────
# Replace the topmost changelog date with today's date so the user can
# tell which version they have. Conservative: only touch the v3 line if
# it exists; otherwise do nothing.
import re
m = re.search(r"(\d{4}-\d{2}-\d{2})\s*\n--\s*v3\.\d+.*Tag search", plugin)
# Don't rewrite — let the user see this is the "Tag Search" version.

with open(PLUGIN, "w", encoding="utf-8") as f:
    f.write(plugin)
print("Wrote: %s  (%d lines)" % (PLUGIN, plugin.count("\n") + 1))
